#!/usr/bin/env node
// CT-104: writes tests/fixtures/evm-eip712.json, the cross-check between viem and the Rust EIP-712 code of
// `x207-circle/src/evm.rs`. The key is a public test key; nothing here is secret.
//
//   VIEM_DIR=/path/with/node_modules node scripts/gen-evm-vectors.mjs
//
// `VIEM_DIR` is a folder whose `node_modules` has `viem` (the contracts repo does not depend on it).
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(join(process.env.VIEM_DIR ?? process.cwd(), 'noop.js'));
const { hashDomain, hashTypedData, keccak256, toHex } = require('viem');
const { privateKeyToAccount } = require('viem/accounts');

const KEY = '0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d'; // public hardhat test key
const account = privateKeyToAccount(KEY);
const address = account.address.toLowerCase();
const CIRCLE = 'x207-v014.testnet';
// salt = keccak256("near:" + network + ":" + contract account id); network = testnet for *.testnet, else mainnet
const saltOf = (network, contract) => keccak256(toHex(`near:${network}:${contract}`));
const domainOf = (contract) => ({ name: 'x207', version: '1', salt: saltOf(contract.endsWith('.testnet') ? 'testnet' : 'mainnet', contract) });
const domain = domainOf(CIRCLE);
const types = {
  Voucher: [
    { name: 'circle', type: 'string' }, { name: 'payer', type: 'string' }, { name: 'payee', type: 'string' },
    { name: 'epoch', type: 'uint64' }, { name: 'seq', type: 'uint64' }, { name: 'cumulativeAmount', type: 'uint256' },
    { name: 'unit', type: 'string' }, { name: 'resource', type: 'string' },
  ],
  Bundle: [{ name: 'circle', type: 'string' }, { name: 'message', type: 'string' }, { name: 'termsHash', type: 'string' }],
  Action: [
    { name: 'circle', type: 'string' }, { name: 'member', type: 'string' }, { name: 'action', type: 'string' },
    { name: 'epoch', type: 'uint64' }, { name: 'receiver', type: 'string' }, { name: 'termsHash', type: 'string' },
    { name: 'nonce', type: 'uint64' }, { name: 'deadline', type: 'uint64' }, { name: 'maxFee', type: 'uint256' },
  ],
};

async function entry(primaryType, message) {
  const typed = { domain, types, primaryType, message };
  return {
    primaryType,
    message: Object.fromEntries(Object.entries(message).map(([k, v]) => [k, typeof v === 'bigint' ? v.toString() : v])),
    digest: hashTypedData(typed),
    signature: await account.signTypedData(typed),
  };
}

const termsMessage = '{"circle":"x207-v014.testnet","epoch":3,"legs":[{"payer":"a.testnet","payee":"b.testnet","amount":"5000000"}]}';
const termsHash = createHash('sha256').update(termsMessage).digest('hex');
const payee = 'gpu.testnet';
const joinTerms = 'a'.repeat(64);

const out = {
  note: 'Generated by scripts/gen-evm-vectors.mjs with viem; the Rust code in x207-circle/src/evm.rs must match byte for byte.',
  domainSeparator: hashDomain({ domain, types: { EIP712Domain: [{ name: 'name', type: 'string' }, { name: 'version', type: 'string' }, { name: 'salt', type: 'bytes32' }] } }),
  circle: CIRCLE,
  salt: domain.salt,
  address,
  vectors: {
    voucher: await entry('Voucher', { circle: CIRCLE, payer: address, payee, epoch: 4n, seq: 2n, cumulativeAmount: 12345678901234567890123n, unit: 'credit', resource: '/api/translate?lang=id' }),
    bundle: { termsMessage, ...(await entry('Bundle', { circle: CIRCLE, message: termsMessage, termsHash })) },
    join: await entry('Action', { circle: CIRCLE, member: address, action: 'join', epoch: 0n, receiver: '', termsHash: joinTerms, nonce: 0n, deadline: 1900000000000n, maxFee: 0n }),
    claim: await entry('Action', { circle: CIRCLE, member: address, action: 'claim', epoch: 5n, receiver: 'agent.testnet', termsHash: '', nonce: 0n, deadline: 1900000000000n, maxFee: 250000n }),
    request_exit: await entry('Action', { circle: CIRCLE, member: address, action: 'request_exit', epoch: 0n, receiver: '', termsHash: '', nonce: 1n, deadline: 1900000000000n, maxFee: 0n }),
    auto_settle: await entry('Action', { circle: CIRCLE, member: address, action: 'auto_settle', epoch: 0n, receiver: '', termsHash: '', nonce: 3n, deadline: 1900000000000n, maxFee: 0n }),
    auto_settle_off: await entry('Action', { circle: CIRCLE, member: address, action: 'auto_settle_off', epoch: 0n, receiver: '', termsHash: '', nonce: 4n, deadline: 1900000000000n, maxFee: 0n }),
    withdraw_stake: await entry('Action', { circle: CIRCLE, member: address, action: 'withdraw_stake', epoch: 0n, receiver: 'agent.testnet', termsHash: '', nonce: 2n, deadline: 1900000000000n, maxFee: 100000n }),
  },
};
out.vectors.bundle.termsHash = termsHash;

// the voucher signed for other contracts: same message, other domain salt (only `circle` differs on purpose? no: the message is identical)
{
  const m = out.vectors.voucher.message;
  const typedFor = (contract) => ({ domain: domainOf(contract), types, primaryType: 'Voucher', message: { ...m, epoch: BigInt(m.epoch), seq: BigInt(m.seq), cumulativeAmount: BigInt(m.cumulativeAmount) } });
  out.crossContract = {};
  for (const contract of ['other-circle.testnet', 'x207-v014.near']) {
    out.crossContract[contract] = { salt: domainOf(contract).salt, digest: hashTypedData(typedFor(contract)), signature: await account.signTypedData(typedFor(contract)) };
  }
}

// the same signature with s replaced by n - s and the other v: valid for ecrecover, refused when malleability is checked
const N = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n;
const sig = out.vectors.voucher.signature;
const flippedS = (N - BigInt(`0x${sig.slice(66, 130)}`)).toString(16).padStart(64, '0');
const flippedV = (parseInt(sig.slice(130, 132), 16) === 27 ? 28 : 27).toString(16);
out.vectors.voucher.highSSignature = `0x${sig.slice(2, 66)}${flippedS}${flippedV}`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'fixtures', 'evm-eip712.json');
writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${target}`);
